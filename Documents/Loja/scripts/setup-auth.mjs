function hashPassword(password) {
  const salt = randomBytes(16).toString("hex");
  const hash = scryptSync(password, salt, 64).toString("hex");
  return `scrypt:${salt}:${hash}`;
}

function randomPassword() {
  return randomBytes(18).toString("base64url");
}

function parseArgs(values) {
  const result = {};
  for (let index = 0; index < values.length; index += 1) {
    if (values[index] === "--email") {
      result.email = values[index + 1];
      index += 1;
    } else if (values[index] === "--password") {
      result.password = values[index + 1];
      index += 1;
    }
  }
  return result;
}

function parseEnv(contents) {
  return contents.split(/\r?\n/).reduce((acc, line) => {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#") || !trimmed.includes("=")) {
      return acc;
    }
    const [key, ...rest] = trimmed.split("=");
    acc[key] = rest.join("=");
    return acc;
  }, {});
}

function preserveUnknown(env) {
  const known = new Set([
    "NEXT_PUBLIC_SITE_URL",
    "NEXT_PUBLIC_STRIPE_PUBLISHABLE_KEY",
    "STRIPE_SECRET_KEY",
    "STRIPE_WEBHOOK_SECRET",
    "ADMIN_EMAIL",
    "ADMIN_PASSWORD_HASH",
    "ADMIN_SESSION_SECRET"
  ]);
  return Object.fromEntries(Object.entries(env).filter(([key]) => !known.has(key)));
}

function serializeEnv(env) {
  const lines = [
    "# Generated by npm run setup",
    ...Object.entries(env).map(([key, value]) => `${key}=${value}`)
  ];
  return `${lines.join("\n")}\n`;
}
