import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { randomBytes, scryptSync } from "node:crypto";
import { resolve } from "node:path";

const envPath = resolve(process.cwd(), ".env.local");
const args = parseArgs(process.argv.slice(2));
const existing = existsSync(envPath) ? parseEnv(readFileSync(envPath, "utf8")) : {};

const adminEmail = args.email || existing.ADMIN_EMAIL || "admin@example.com";
const adminPassword = args.password || randomPassword();
const sessionSecret = existing.ADMIN_SESSION_SECRET || randomBytes(48).toString("base64url");
const passwordHash = hashPassword(adminPassword);

const nextEnv = {
  NEXT_PUBLIC_SITE_URL: existing.NEXT_PUBLIC_SITE_URL || "http://localhost:3000",
  NEXT_PUBLIC_STRIPE_PUBLISHABLE_KEY: existing.NEXT_PUBLIC_STRIPE_PUBLISHABLE_KEY || "pk_test_replace_me",
  STRIPE_SECRET_KEY: existing.STRIPE_SECRET_KEY || "sk_test_replace_me",
  STRIPE_WEBHOOK_SECRET: existing.STRIPE_WEBHOOK_SECRET || "whsec_replace_me",
  ADMIN_EMAIL: adminEmail,
  ADMIN_PASSWORD_HASH: passwordHash,
  ADMIN_SESSION_SECRET: sessionSecret,
  ...preserveUnknown(existing)
};

writeFileSync(envPath, serializeEnv(nextEnv), "utf8");

console.log("Auth setup concluído.");
console.log(`Ficheiro: ${envPath}`);
console.log(`ADMIN_EMAIL=${adminEmail}`);
console.log(`ADMIN_PASSWORD=${adminPassword}`);
